"""Generate src/generated/leafletCss.ts (Leaflet's stylesheet as a string) from node_modules/leaflet.

The extension build cannot bundle CSS that references images, so the Flight Map panel injects this string
itself; the image references (layer switcher icon, default marker) are dropped, the panel does not use them.
Re-run after updating leaflet:
    python3 scripts/gen_leaflet_css.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSS = ROOT / "node_modules" / "leaflet" / "dist" / "leaflet.css"
OUT = ROOT / "src" / "generated" / "leafletCss.ts"

css = CSS.read_text()
css = re.sub(r"^\s*background-image:\s*url\([^)]*\);\s*$", "", css, flags=re.MULTILINE)
version = json.loads((CSS.parent.parent / "package.json").read_text())["version"]

OUT.write_text(
    f"// Generated by scripts/gen_leaflet_css.py from leaflet {version}, do not edit by hand.\n\n"
    f"export const LEAFLET_CSS = {json.dumps(css)};\n"
)
print(f"wrote {OUT}")
