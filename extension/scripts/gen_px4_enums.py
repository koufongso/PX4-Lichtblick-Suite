"""Generate src/generated/px4Enums.ts (value -> name tables) from the px4_msgs .msg files.

Re-run whenever PX4 (and so px4_msgs) is updated, so the names shown in Lichtblick match the firmware:
    python3 scripts/gen_px4_enums.py <path to px4_msgs/msg>
"""
import re
import sys
from pathlib import Path

# (export name, .msg file, constant prefix)
ENUMS = [
    ("NAVIGATION_STATE", "VehicleStatus.msg", "NAVIGATION_STATE_"),
    ("ARMING_STATE", "VehicleStatus.msg", "ARMING_STATE_"),
    ("VEHICLE_VTOL_STATE", "VtolVehicleStatus.msg", "VEHICLE_VTOL_STATE_"),
    ("BATTERY_WARNING", "BatteryStatus.msg", "WARNING_"),
]
# placeholders and bounds, not states
SKIP = re.compile(r"(^FREE\d*$|^MAX$)")
CONSTANT = re.compile(r"^\s*u?int\d+\s+([A-Z0-9_]+)\s*=\s*(\d+)")

OUT = Path(__file__).resolve().parent.parent / "src" / "generated" / "px4Enums.ts"


def read_enum(msg_file: Path, prefix: str) -> dict[int, str]:
    values = {}
    for line in msg_file.read_text().splitlines():
        match = CONSTANT.match(line)
        if not match or not match.group(1).startswith(prefix):
            continue
        name = match.group(1)[len(prefix):]
        if not SKIP.match(name):
            values.setdefault(int(match.group(2)), name)
    return values


def main(msg_dir: Path) -> None:
    lines = [
        f"// Generated by scripts/gen_px4_enums.py from {msg_dir.name}/ of px4_msgs, do not edit by hand.",
        "",
    ]
    for export_name, msg_name, prefix in ENUMS:
        values = read_enum(msg_dir / msg_name, prefix)
        if not values:
            sys.exit(f"no {prefix}* constants found in {msg_name}")
        lines.append(f"// {msg_name}: {prefix}*")
        lines.append(f"export const {export_name}: Readonly<Record<number, string>> = {{")
        lines += [f'  {value}: "{name}",' for value, name in sorted(values.items())]
        lines += ["};", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(Path(sys.argv[1]))
